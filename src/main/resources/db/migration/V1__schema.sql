create table design_session (
  id              varchar(40) primary key,
  token_hash      varchar(128) not null,
  head_version_id varchar(40),
  ai_calls        int not null default 0,
  created_at      timestamp with time zone not null
);

create table design_version (
  id               varchar(40) primary key,
  session_id       varchar(40) not null references design_session(id),
  seq              int not null,
  parent_id        varchar(40),
  input_text       varchar(500),
  spec_json        text not null,
  plan_json        text not null,
  estimate_json    text not null,
  diff_json        text,
  explanation_json text,
  expected_ngn     bigint not null,
  budget_status    varchar(10),
  created_at       timestamp with time zone not null,
  constraint uq_version_seq unique (session_id, seq)
);
create index ix_version_session on design_version(session_id);

create table price_item (
  id          bigint generated by default as identity primary key,
  price_key   varchar(60)  not null,
  grp         varchar(30)  not null,
  description varchar(200) not null,
  unit        varchar(10)  not null,
  region      varchar(20)  not null,
  finish      varchar(10)  not null,   -- basic | standard | premium | any
  rate_ngn    bigint       not null check (rate_ngn > 0),
  source      varchar(200) not null,
  supplier    varchar(120),
  observed_on date         not null,
  verified    boolean      not null default false,
  constraint uq_price unique (price_key, region, finish)
);
